last_argument() {
  printf "%s" "${@: -1}"
}

format_with_style() {
  local formatter="$1"
  shift

  if [ "$USE_COLOR" = "true" ] && command -v "$formatter" >/dev/null 2>&1; then
    "$formatter" "$@"
  else
    last_argument "$@"
  fi
}

