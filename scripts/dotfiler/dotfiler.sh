  local tmp_script="$1"
  local started_at_seconds
  started_at_seconds=$(date +%s)

  if ! grep -Eq 'SymbolicLink|HardLink' "$tmp_script"; then
    return 0
  fi

  if [ "$DRY_RUN" = "true" ]; then
    log_info_action "Simulación: se omite la ejecución de PowerShell elevado."
