# terminals render two columns wide, which keeps columns aligned.
ICON_APP=${ICON_APP:-"🔗"}
ICON_REAL_RUN=${ICON_REAL_RUN:-"🚀"}
ICON_DRY_RUN=${ICON_DRY_RUN:-"🧪"}
