ICON_DELETE=${ICON_DELETE:-"🧹"}
ICON_BACKUP=${ICON_BACKUP:-"💾"}
ICON_DIRECTORY=${ICON_DIRECTORY:-"📂"}
ICON_SUDO=${ICON_SUDO:-"🔐"}
ICON_QUEUED=${ICON_QUEUED:-"🪟"}
ICON_WARN=${ICON_WARN:-"🚨"}
ICON_ERROR=${ICON_ERROR:-"❌"}
