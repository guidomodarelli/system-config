  format_with_style "logGray" "$@"
}

normalize_display_path() {
  local path="$1"

  if [[ "$path" == *\\* ]]; then
    printf "%s" "$path"
    return 0
  fi

  printf "%s" "$path" | sed -E -e 's#/+#/#g' -e ':collapse' -e 's#/\./#/#' -e 't collapse' -e 's#(.)/\.$#\1#'
}

abbreviate_home_path() {
  local path="$1"
  local home_path

  for home_path in "$HOME" "$(realpath "$HOME" 2>/dev/null)"; do
    [ -z "$home_path" ] && continue
    if [ "$path" = "$home_path" ] || [[ "$path" == "$home_path"/* ]]; then
      printf "%s" "~${path#"$home_path"}"
      return 0
    fi
  done

  printf "%s" "$path"
}

print_path() {
  local path="$1"
  local normalized_path
  normalized_path=$(normalize_display_path "$path")

  if [ "$USE_PATH_STYLE" = "true" ] && [ "$USE_COLOR" = "true" ] && command -v styleText >/dev/null 2>&1; then
    styleText -u -i -- "$normalized_path"
  else
    printf "%s" "$normalized_path"
  fi
}

build_icon() {
  local icon_value="$1"

  if [ "$USE_ICONS" = "true" ]; then
    printf "%s" "$icon_value"
  fi
}

can_print_details() {
  if [ "$QUIET" = "true" ]; then
    return 1
  fi
  return 0
}

# Pads text to a width counted in characters (printf pads by bytes, which
# misaligns accented text).
pad_text() {
  local text="$1"
  local width="$2"
  local padding=$((width - ${#text}))

  if [ "$padding" -le 0 ]; then
    printf "%s" "$text"
    return 0
  fi
  printf "%s%*s" "$text" "$padding" ""
}

display_target_path() {
  normalize_display_path "$(abbreviate_home_path "$1")"
}

# Shows sources relative to the repository configs directory, or with `~`
# for paths inside HOME.
display_source_path() {
  local path="$1"

  if [[ "$path" == "$ROOT_CONFIGS_DIR/"* ]]; then
    path="${path#"$ROOT_CONFIGS_DIR/"}"
  else
    path=$(abbreviate_home_path "$path")
  fi

  normalize_display_path "$path"
}

# Prints an emoji followed by a space, or nothing with --plain.
icon_prefix() {
  if [ "$USE_ICONS" = "true" ] && [ -n "$1" ]; then
    printf "%s " "$1"
  fi
}

repeat_text() {
  local text="$1"
  local count="$2"
  local result=""
  while [ "$count" -gt 0 ]; do
    result="$result$text"
    count=$((count - 1))
  done
  printf "%s" "$result"
}

# Boxes are open on the right: emoji width varies between terminals, so only
# the left border and the horizontal rules are drawn.
print_box_top() {
  clear_status_line
  local title="$1"
  local title_length=${#title}
  local rule_length=$((BOX_RULE_WIDTH - title_length - 4))
  if [ -z "$title" ]; then
    printf "%s\n" "$(print_gray -b "$BOX_TOP_LEFT$(repeat_text "$BOX_HORIZONTAL" "$BOX_RULE_WIDTH")")"
    return 0
  fi
  printf "%s %s %s\n" \
    "$(print_gray -b "$BOX_TOP_LEFT$BOX_HORIZONTAL")" \
    "$(print_blue -b "$title")" \
    "$(print_gray -b "$(repeat_text "$BOX_HORIZONTAL" "$rule_length")")"
}

print_box_row() {
  clear_status_line
  printf "%s %s\n" "$(print_gray -b "$BOX_VERTICAL")" "$1"
}

print_box_divider() {
  clear_status_line
  printf "%s\n" "$(print_gray -b "$BOX_TEE$(repeat_text "$BOX_HORIZONTAL" "$BOX_RULE_WIDTH")")"
}

print_box_bottom() {
  clear_status_line
  printf "%s\n" "$(print_gray -b "$BOX_BOTTOM_LEFT$(repeat_text "$BOX_HORIZONTAL" "$BOX_RULE_WIDTH")")"
}

progress_is_enabled() {
  case "$DOTFILER_PROGRESS" in
  always) return 0 ;;
  never) return 1 ;;
  esac
  [ "$QUIET" != "true" ] && [ "$DEBUG" != "true" ] && [ -t 2 ]
}

clear_status_line() {
  if [ "$STATUS_LINE_ACTIVE" = "true" ]; then
    printf "\r\033[K" >&2
    STATUS_LINE_ACTIVE="false"
  fi
}

truncate_text() {
  local text="$1"
  local max_length="$2"
  if [ "${#text}" -le "$max_length" ]; then
    printf "%s" "$text"
    return 0
  fi
  printf "%s%s" "${text:0:$((max_length - ${#DISPLAY_ELLIPSIS}))}" "$DISPLAY_ELLIPSIS"
}

build_progress_bar() {
  local current="$1"
  local total="$2"
  local filled=0
  if [ "$total" -gt 0 ]; then
    filled=$((current * PROGRESS_BAR_WIDTH / total))
  fi
  printf "%s%s" "$(repeat_text "$PROGRESS_BAR_FILLED" "$filled")" "$(repeat_text "$PROGRESS_BAR_EMPTY" $((PROGRESS_BAR_WIDTH - filled)))"
}

# Renders one status line on stderr: spinner frame, message, progress bar,
# counter, current item and elapsed seconds. It is overwritten in place.
render_status_line() {
  local frame="$1"
  local icon="$2"
  local message="$3"
  local current="$4"
  local total="$5"
  local detail="$6"
  local elapsed_seconds="$7"

  local progress_text=""
  if [ -n "$total" ] && [ "$total" -gt 0 ]; then
    progress_text=" $(print_blue -b "$(build_progress_bar "$current" "$total")") $current/$total"
  fi
  local detail_text=""
  if [ -n "$detail" ]; then
    detail_text=" $(print_gray -b "$DISPLAY_SEPARATOR $(truncate_text "$detail" "$PROGRESS_DETAIL_MAX_LENGTH")")"
  fi
  local elapsed_text=""
  if [ -n "$elapsed_seconds" ]; then
    elapsed_text=" $(print_gray -b "$(icon_prefix "$ICON_TIME")${elapsed_seconds}s")"
  fi

  printf "\r\033[K%s %s%s%s%s" "$(print_magenta -b "$frame")" "$(icon_prefix "$icon")$message" "$progress_text" "$detail_text" "$elapsed_text" >&2
}

# Animates a spinner in the background while paths are resolved. Messages
# rotate every few seconds and the current entry is read from a progress file
# written by get_paths.
start_spinner() {
  progress_is_enabled || return 0
  printf "\033[?25l" >&2

  (
    trap 'exit 0' TERM
    local tick=0
    local started_at_seconds
    started_at_seconds=$(date +%s)
    local frame_count=${#SPINNER_FRAMES[@]}
    local message_count=${#RESOLVE_MESSAGE_TEXTS[@]}
    local progress_line current total detail
    while true; do
      local message_index=$(((tick / SPINNER_TICKS_PER_MESSAGE) % message_count))
      progress_line=""
      if [ -s "$RESOLVE_PROGRESS_FILE" ]; then
        IFS= read -r progress_line < "$RESOLVE_PROGRESS_FILE"
      fi
      current="${progress_line%%/*}"
      total="${progress_line#*/}"
      total="${total%% *}"
      detail="${progress_line#* }"
      if [ -z "$progress_line" ]; then
        current=""
        total=""
        detail=""
      fi
      render_status_line "${SPINNER_FRAMES[$((tick % frame_count))]}" \
        "${RESOLVE_MESSAGE_ICONS[$message_index]}" "${RESOLVE_MESSAGE_TEXTS[$message_index]}" \
        "$current" "$total" "$detail" "$(($(date +%s) - started_at_seconds))"
      sleep "$SPINNER_TICK_SECONDS"
      tick=$((tick + 1))
    done
  ) &
  SPINNER_PID=$!
  STATUS_LINE_ACTIVE="true"
}

stop_spinner() {
  if [ -n "$SPINNER_PID" ]; then
    kill "$SPINNER_PID" 2>/dev/null
    wait "$SPINNER_PID" 2>/dev/null
    SPINNER_PID=""
    STATUS_LINE_ACTIVE="true"
  fi
  clear_status_line
  if progress_is_enabled; then
    printf "\033[?25h" >&2
  fi
}

# Synchronous progress for the linking loop: redrawn before each operation and
# cleared by any regular output line.
render_linking_progress() {
  local current="$1"
  local total="$2"
  local item_name="$3"
  progress_is_enabled || return 0
  render_status_line "${SPINNER_FRAMES[$((current % ${#SPINNER_FRAMES[@]}))]}" \
    "$ICON_LINKING" "Enlazando" "$current" "$total" "$item_name" ""
  STATUS_LINE_ACTIVE="true"
}

# Prints one operation line: icon, action label, item name and optional detail.
print_item_line() {
  local color_function="$1"
  local icon="$2"
  local label="$3"
  local name="$4"
  local detail="${5:-}"

  can_print_details || return 0
  print_pending_group_header
  GROUP_CHANGE_COUNT=$((GROUP_CHANGE_COUNT + 1))

  local item_text="$name"
  if [ -n "$detail" ]; then
    item_text="$(pad_text "$name" "$ITEM_NAME_WIDTH") $(print_gray -b "$detail")"
  fi

  print_box_row "$(icon_prefix "$icon")$("$color_function" -b "$(pad_text "$label" "$ACTION_LABEL_WIDTH")") $item_text"
  LAST_OUTPUT_WAS_BLANK=false
}

print_link_detail() {
  local source_path="$1"
  local link_type="$2"
  local detail
  detail="$POINTER $(display_source_path "$source_path")"
  if [ "$link_type" = "$LINK_TYPE_HARD" ]; then
    detail="$detail ($LINK_TYPE_HARD)"
  fi
  printf "%s" "$detail"
}

print_block_gap() {
  if can_print_details && [ "$LAST_OUTPUT_WAS_BLANK" != "true" ]; then
    clear_status_line
    printf "\n"
    LAST_OUTPUT_WAS_BLANK=true
  fi
}

log_info_action() {
  local message="$1"
  clear_status_line
  if can_print_details; then
    printf "  %s\n" "$(print_gray -b "$message")"
    LAST_OUTPUT_WAS_BLANK=false
  fi
}




log_warn_action() {
  local message="$1"
  clear_status_line
  printf "%s %s\n" "$(print_yellow -b "$(icon_prefix "$ICON_WARN")Aviso:")" "$message" >&2
  LAST_OUTPUT_WAS_BLANK=false
}

log_error_action() {
  local message="$1"
  clear_status_line
  printf "%s %s\n" "$(print_red -b "$(icon_prefix "$ICON_ERROR")Error:")" "$message" >&2
  LAST_OUTPUT_WAS_BLANK=false
}

# Registers the group header; it is printed lazily before the first visible
# line of the group, so groups where nothing changed stay hidden.
print_group_header() {
  PENDING_GROUP_HEADER="$1"
  if [ "$VERBOSE" = "true" ]; then
    print_pending_group_header
  fi
}

print_pending_group_header() {
  if [ -z "$PENDING_GROUP_HEADER" ] || ! can_print_details; then
    return 0
  fi

  local group_path="$PENDING_GROUP_HEADER"
  PENDING_GROUP_HEADER=""
  GROUP_CHANGE_COUNT=0
  LAST_GROUP_OPEN="true"
  print_block_gap
  clear_status_line
  printf "%s\n" "$(print_magenta -b "$(icon_prefix "$ICON_GROUP")$(normalize_display_path "$group_path")")"
  LAST_OUTPUT_WAS_BLANK=false
}

# Prints the aggregated count of links that were already correct in the
# current group, only when the group also had visible changes. With
# --verbose each unchanged link is listed instead.
# Closes the current group box with its change and unchanged counts. Groups
# where nothing changed were never opened, unless --verbose is active.
flush_group_unchanged_count() {
  if [ -z "$PENDING_GROUP_HEADER" ] && [ "$LAST_GROUP_OPEN" = "true" ] && can_print_details; then
    local closing_parts=()
    if [ "$VERBOSE" != "true" ] && [ "$GROUP_CHANGE_COUNT" -gt 0 ]; then
      closing_parts+=("$GROUP_CHANGE_COUNT $(pluralize "$GROUP_CHANGE_COUNT" "cambio" "cambios")")
    fi
    if [ "$GROUP_UNCHANGED_COUNT" -gt 0 ]; then
      closing_parts+=("$(icon_prefix "$ICON_UNCHANGED")$GROUP_UNCHANGED_COUNT sin cambios")
    fi

    local closing_text=""
    local closing_part
    for closing_part in "${closing_parts[@]}"; do
      if [ -z "$closing_text" ]; then
        closing_text="$closing_part"
      else
        closing_text="$closing_text $DISPLAY_SEPARATOR $closing_part"
      fi
    done
    clear_status_line
    printf "%s %s\n" "$(print_gray -b "$BOX_BOTTOM_LEFT$BOX_HORIZONTAL")" "$(print_gray -b "$closing_text")"
    LAST_OUTPUT_WAS_BLANK=false
  fi
  GROUP_UNCHANGED_COUNT=0
  GROUP_CHANGE_COUNT=0
  PENDING_GROUP_HEADER=""
  LAST_GROUP_OPEN="false"
}

pluralize() {
  if [ "$1" -eq 1 ]; then
    printf "%s" "$2"
  else
    printf "%s" "$3"
  fi
}


print_operation_duration() {
  local started_at_seconds="$1"

  if [ "$VERBOSE" = "true" ] && can_print_details; then
    local ended_at_seconds
    ended_at_seconds=$(date +%s)
    local elapsed_seconds=$((ended_at_seconds - started_at_seconds))
    print_box_row "   $(print_gray -b "$(icon_prefix "$ICON_TIME")transcurrido=${elapsed_seconds}s")"
    LAST_OUTPUT_WAS_BLANK=false
  fi
}

# Replaces emoji decorations with narrow Unicode symbols (--unicode) or plain
# ASCII (--ascii) for terminals without emoji or Unicode fonts. Texts keep
# their Spanish accents: only decorations change.
apply_icon_mode() {
  case "$ICON_MODE" in
  unicode)
    ICON_APP="" ICON_REAL_RUN="▶" ICON_DRY_RUN="◇" ICON_SOURCE="" ICON_HOME=""
    ICON_GROUP="▸" ICON_CREATED="+" ICON_REPLACED="↻" ICON_UNCHANGED="✓"
    ICON_DELETE="✗" ICON_BACKUP="↺" ICON_DIRECTORY="▪" ICON_SUDO="!"
    ICON_QUEUED="⇢" ICON_WARN="▲" ICON_ERROR="✗" ICON_TIME="" ICON_SUMMARY=""
    ICON_DIAGNOSTIC="" ICON_DONE="✓" ICON_FAILED="✗" ICON_LINKING="⇢"
    RESOLVE_MESSAGE_ICONS=("" "" "" "" "")
    ;;
  ascii)
    ICON_APP="" ICON_REAL_RUN=">" ICON_DRY_RUN="~" ICON_SOURCE="" ICON_HOME=""
    ICON_GROUP=">" ICON_CREATED="+" ICON_REPLACED="~" ICON_UNCHANGED="="
    ICON_DELETE="x" ICON_BACKUP="<" ICON_DIRECTORY="#" ICON_SUDO="!"
    ICON_QUEUED=">" ICON_WARN="!" ICON_ERROR="x" ICON_TIME="" ICON_SUMMARY=""
    ICON_DIAGNOSTIC="" ICON_DONE="=" ICON_FAILED="x" ICON_LINKING=">"
    RESOLVE_MESSAGE_ICONS=("" "" "" "" "")
    BOX_TOP_LEFT="+" BOX_BOTTOM_LEFT="+" BOX_VERTICAL="|" BOX_TEE="+" BOX_HORIZONTAL="-"
    SPINNER_FRAMES=("|" "/" "-" "\\")
    PROGRESS_BAR_FILLED="#" PROGRESS_BAR_EMPTY="."
    POINTER="->" DISPLAY_SEPARATOR="-" DISPLAY_ELLIPSIS="..."
    ;;
  esac
}

set_icon_mode() {
  local requested_mode="$1"
  if [ "$ICON_MODE" != "emoji" ] && [ "$ICON_MODE" != "$requested_mode" ]; then
    log_error_action "Las opciones --ascii y --unicode son excluyentes: usá solo una."
    exit "$EXIT_CODE_INPUT_ERROR"
  fi
  ICON_MODE="$requested_mode"
}

print_help() {
  cat <<'USAGE'
Uso: ./scripts/dotfiler/dotfiler.sh [opciones]

Opciones:
  --dry-run   Muestra los cambios planificados sin escribir archivos
  --no-color  Desactiva los estilos ANSI
  --plain     Desactiva estilos, íconos y énfasis de rutas
  --unicode   Usa símbolos Unicode sin emojis (terminales sin fuente de emojis)
  --ascii     Usa solo ASCII en íconos, cajas y loader (terminales sin Unicode)
  --verbose   Lista también los enlaces sin cambios y el tiempo por operación
  --quiet     Oculta logs por ítem y muestra solo resumen/errores
  --help      Muestra esta ayuda

--unicode y --ascii son excluyentes.

Variables:
  DOTFILER_PROGRESS=auto|always|never  Loader animado (auto: solo en terminal interactiva)
USAGE
}

parse_args() {
  while [ $# -gt 0 ]; do
    case "$1" in
    --dry-run)
      DRY_RUN=true
      ;;
    --no-color)
      USE_COLOR=false
      USE_PATH_STYLE=false
      ;;
    --plain)
      USE_COLOR=false
      USE_ICONS=false
      USE_PATH_STYLE=false
      ;;
    --unicode)
      set_icon_mode "unicode"
      ;;
    --ascii)
      set_icon_mode "ascii"
      ;;
    --verbose)
      VERBOSE=true
      ;;
    --quiet)
      QUIET=true
      ;;
    --help)
      print_help
      exit 0
      ;;
    *)
      log_error_action "Opción desconocida: $1"
      print_help
      exit "$EXIT_CODE_INPUT_ERROR"
      ;;
    esac
    shift
  done
}

record_failed_target() {
  local target="$1"
  local reason="$2"
  printf "%s\t%s\n" "$target" "$reason" >> "$FAILED_TARGETS_FILE"
}

# Counts entries persisted in $FAILED_TARGETS_FILE.
# Used to recover failure counts that were incremented inside command
# substitution subshells (e.g. retrieve_paths_for_platform), where
# changes to COUNT_ERRORS are otherwise lost.
recorded_failure_count() {
  if [ ! -s "$FAILED_TARGETS_FILE" ]; then
    echo 0
    return 0
  fi
  awk 'NF { count++ } END { print count + 0 }' "$FAILED_TARGETS_FILE"
}

validate_paths_config() {
  if [ ! -f "$CONFIG_PATHS_FILE" ]; then
    log_error_action "No se encontró el archivo de configuración: $(print_path "$CONFIG_PATHS_FILE")"
    return 1
  fi

  if ! yq eval '.paths' "$CONFIG_PATHS_FILE" >/dev/null 2>&1; then
    log_error_action "Configuración inválida en $(print_path "$CONFIG_PATHS_FILE"): no se pudo interpretar YAML."
    return 1
  fi

  if ! yq eval -o=json '.paths' "$CONFIG_PATHS_FILE" | jq -e 'type == "array"' >/dev/null 2>&1; then
    log_error_action "Configuración inválida en $(print_path "$CONFIG_PATHS_FILE"): 'paths' debe ser un arreglo."
    return 1
  fi

  return 0
}

# Restrict distro name to a conservative charset to prevent path / PowerShell
# injection when the value flows into the elevated script generation.
SAFE_WSL_DISTRO_REGEX='^[A-Za-z0-9._-]+$'

is_safe_wsl_distro_name() {
  [[ "$1" =~ $SAFE_WSL_DISTRO_REGEX ]]
}

# Get the current WSL distribution name
get_wsl_distro_name() {
  is_wsl || return 0

  local candidate=""

  if [ -n "$WSL_DISTRO_NAME" ]; then
    candidate="$WSL_DISTRO_NAME"
  fi

  if [ -z "$candidate" ]; then
    local win_root
    win_root=$(wslpath -w / 2>/dev/null)
    local distro_regex='^\\\\wsl(\\\\.localhost)?\\\\([^\\\\]+)\\\\'
    if [[ $win_root =~ $distro_regex ]]; then
      candidate="${BASH_REMATCH[2]}"
    fi
  fi

  if [ -z "$candidate" ]; then
    candidate=$(awk -F= '/^NAME=/ { gsub(/"/, "", $2); print $2; exit }' /etc/os-release | tr -d '\r\n')
  fi

  if ! is_safe_wsl_distro_name "$candidate"; then
    log_error_action "Nombre de distribución WSL inválido o inseguro: $candidate"
    return 1
  fi

  echo "$candidate"
}

# Format path for Windows when in WSL
format_wsl_windows_path() {
  local path="$1"
  local distro_name
  if ! distro_name=$(get_wsl_distro_name); then
    return 1
  fi

  if ! is_safe_wsl_distro_name "$distro_name"; then
    log_error_action "Nombre de distribución WSL inválido o inseguro: $distro_name"
    return 1
  fi

  path="\\\\wsl\$\\$distro_name$path"
  path="${path//\//\\}"

  echo "$path"
}

# Returns a backup path that does not collide with an existing entry.
# Mirrors Resolve-BackupPath in dotfiler.ps1 so a previous .bak is never overwritten.
resolve_backup_path() {
  local target="$1"
  local candidate="${target}.bak"
  local suffix=1

  while [ -e "$candidate" ] || [ -L "$candidate" ]; do
    candidate="${target}.bak.${suffix}"
    suffix=$((suffix + 1))
  done

  printf "%s" "$candidate"
}

create_backup() {
  local path="$1"
  shift
  local -a command_prefix=("$@")
  local backup_path
  backup_path=$(resolve_backup_path "$path")

  if [ "$DRY_RUN" = "true" ]; then
    COUNT_BACKUPS=$((COUNT_BACKUPS + 1))
    print_item_line print_yellow "$ICON_BACKUP" "respaldo" "$(basename "$path")" "$POINTER $(basename "$backup_path")"
    return 0
  fi

  if ! "${command_prefix[@]}" mv "${path}" "${backup_path}" 2>/dev/null; then
    log_error_action "No se pudo crear respaldo para $(print_path "$path")"
    record_failed_target "$path" "Fallo al crear respaldo"
    return 1
  fi

  COUNT_BACKUPS=$((COUNT_BACKUPS + 1))
  print_item_line print_yellow "$ICON_BACKUP" "respaldo" "$(basename "$path")" "$POINTER $(basename "$backup_path")"
}

