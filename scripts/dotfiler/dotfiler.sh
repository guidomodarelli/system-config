  local dir="$1"
  local marker="$2"
  [ -z "$marker" ] && return 0
  [ -f "$dir/$marker" ]
}

walk_emissions_recursive() {
  local root="$1"
  local descend_pat="$2"
  local exclude_pat="$3"
  local marker="$4"

  [ ! -d "$root" ] && return 0

  local stack=("$root")
  local emissions=()

  while [ ${#stack[@]} -gt 0 ]; do
    local last_index=$((${#stack[@]} - 1))
    local current="${stack[$last_index]}"
    unset 'stack[last_index]'

    local children=()
    local entry
    shopt -s nullglob dotglob
    for entry in "$current"/*; do
      children+=("$entry")
    done
    shopt -u nullglob dotglob

    if [ ${#children[@]} -gt 1 ]; then
      local sorted=()
      local sorted_line
      while IFS= read -r sorted_line; do
        sorted+=("$sorted_line")
      done < <(printf '%s\n' "${children[@]}" | LC_ALL=C sort)
      children=("${sorted[@]}")
    fi

    local child
    for child in "${children[@]}"; do
      local name
      name=$(basename "$child")
      if folder_is_excluded "$name" "$exclude_pat"; then
        continue
      fi
      if [ -d "$child" ] && [ ! -L "$child" ]; then
        if folder_should_descend "$name" "$descend_pat"; then
          stack+=("$child")
          continue
        fi
        if leaf_has_marker_file "$child" "$marker"; then
          emissions+=("$child")
        fi
      else
        emissions+=("$child")
      fi
    done
  done

  if [ ${#emissions[@]} -gt 0 ]; then
    printf '%s\n' "${emissions[@]}" | LC_ALL=C sort
  fi
}

# Lists the sources a glob entry resolves to, applying descendInto,
# exclude and markerFile filters.
list_glob_sources() {
  local abs_dir_path="$1"
  local descend_pat="$2"
  local exclude_pat="$3"
  local marker="$4"

  if [ -n "$descend_pat" ]; then
    walk_emissions_recursive "$abs_dir_path" "$descend_pat" "$exclude_pat" "$marker"
    return 0
  fi

  local item
  while IFS= read -r item; do
    local name
    name=$(basename "$item")
    if folder_is_excluded "$name" "$exclude_pat"; then
      continue
    fi
    if [ -d "$item" ] && [ ! -L "$item" ] && ! leaf_has_marker_file "$item" "$marker"; then
      continue
    fi
    printf '%s\n' "$item"
  done < <(find "$abs_dir_path" -maxdepth 1 -mindepth 1 | LC_ALL=C sort)
}

symlink_points_to_source() {
  local link_path="$1"
  local source_path="$2"

  [ -L "$link_path" ] || return 1
  [ "$(readlink "$link_path")" = "$source_path" ] && return 0
  [ "$(realpath "$link_path" 2>/dev/null)" = "$(realpath "$source_path" 2>/dev/null)" ]
}

path_ends_with_glob_star() {
  local p="$1"
  [[ "$p" == *"/*" ]]
}

process_path_entry() {
  local line="$1"
  local selector_override="$2"

  local path
  path=$(echo "$line" | jq -r '.path')
  local selected_override
  selected_override=$(echo "$line" | jq -c "first(.overrides[]? | select($selector_override)) // empty")
  local target
  local uses_exact_target="false"
  local hard_link
  hard_link=$(echo "$line" | jq -r 'if .hardLink == true then "true" else "false" end')

  if [ -n "$selected_override" ]; then
    if json_has_key "$selected_override" "exactTarget"; then
      target=$(json_get_value "$selected_override" "exactTarget")
      uses_exact_target="true"
    else
      target=$(json_get_value "$selected_override" "target")
    fi
  elif json_has_key "$line" "exactTarget"; then
    target=$(json_get_value "$line" "exactTarget")
    uses_exact_target="true"
  else
    target=$(json_get_value "$line" "target")
  fi

  if [[ "$target" != WSL://* ]]; then
    if [ "$target" = "null" ]; then
      target="$HOME"
    elif [ "$(first_letter "$target")" != "/" ] && [ "$(first_letter "$target")" != "~" ]; then
      target="$HOME"/"$target"
    fi
  fi

  target=$(expand_env_vars "$target")

  local descend_into_pat=""
  local exclude_pat=""
  local conditional_exclude_pat=""
  local active_conditional_rules=""
  local marker_file=""
  local filter_parse_failed="false"

  if descend_into_pat=$(read_descend_into_pattern "$line"); then
    :
  else
    log_warn_action "Patron regex invalido en descendInto para $path"
    record_failed_target "$path" "Patron regex invalido en descendInto"
    filter_parse_failed="true"
  fi

  if exclude_pat=$(read_exclude_pattern "$line"); then
    :
  else
    log_warn_action "Patron regex invalido en exclude para $path"
    record_failed_target "$path" "Patron regex invalido en exclude"
    filter_parse_failed="true"
  fi

  if active_conditional_rules=$(read_active_conditional_exclude_rules "$line"); then
    conditional_exclude_pat=$(combine_conditional_rule_patterns "$active_conditional_rules")
  else
    log_warn_action "Patron regex invalido en conditionalExcludes para $path"
    record_failed_target "$path" "Patron regex invalido en conditionalExcludes"
    filter_parse_failed="true"
  fi

  if [ "$filter_parse_failed" = "true" ]; then
    echo "[]"
    return 0
  fi

  marker_file=$(read_marker_file "$line")

  local has_filters="false"
  if [ -n "$descend_into_pat" ] || [ -n "$exclude_pat" ] || [ -n "$marker_file" ] ||
    json_has_key "$line" "conditionalExcludes"; then
    has_filters="true"
  fi

  if [ "$has_filters" = "true" ] && ! path_ends_with_glob_star "$path"; then
    log_warn_action "descendInto/markerFile/exclude/conditionalExcludes solo aplican con path terminado en '/*'. Ignorando filtros para: $path"
    descend_into_pat=""
    exclude_pat=""
    conditional_exclude_pat=""
    marker_file=""
  fi

  if [ "$uses_exact_target" = "true" ]; then
    conditional_exclude_pat=""
  fi

  local effective_exclude_pat
  effective_exclude_pat=$(combine_regex_patterns "$exclude_pat" "$conditional_exclude_pat")

  if is_debug; then
    echo "Path: $(print_path "${path//\\/\\\\}")" >&2
    echo "Target: $(print_path "$target")" >&2
    echo "-----------" >&2
  fi

  local output="[]"
  local seen_basenames=$'\n'

  add_with_collision_check() {
    local item="$1"
    if [ "$uses_exact_target" = "true" ]; then
      output=$(add_path_to_output "$item" "$target" "$output" "$uses_exact_target" "$hard_link")
      return
    fi
    local base
    base=$(basename "$item")
    if [[ "$seen_basenames" == *$'\n'"$base"$'\n'* ]]; then
      log_warn_action "Colision de basename '$base' para $path (primero gana, descartando $item)"
      record_failed_target "$target/$base" "Colision de basename: $item"
      return
    fi
    seen_basenames+="$base"$'\n'
    output=$(add_path_to_output "$item" "$target" "$output" "$uses_exact_target" "$hard_link")
  }

  # Emits a removal operation for a previously created symlink whose source
  # is now excluded by an active `conditionalExcludes` rule. Only symlinks
  # pointing to that exact source are touched; regular files are never removed.
  add_stale_symlink_removal() {
    local item="$1"
    local base
    base=$(basename "$item")
    if [[ "$seen_basenames" == *$'\n'"$base"$'\n'* ]]; then
      return
    fi
    local link_path="$target/$base"
    if ! symlink_points_to_source "$link_path" "$item"; then
      return
    fi
    local removal_reason
    removal_reason=$(find_conditional_exclude_reason "$active_conditional_rules" "$abs_dir_path" "$item")
    local removal_obj
    removal_obj=$(jq -n --arg path "$item" --arg target "$link_path" --arg reason "$removal_reason" \
      '{path: $path, target: $target, hardLink: false, remove: true, reason: $reason}')
    output=$(echo "$output" | jq -c ". + [$removal_obj]")
  }

  if [[ "$path" == *"*" ]]; then
    local dir_path="${path%/*}"
    local abs_dir_path
    abs_dir_path=$(get_abs_path "$dir_path")

    if [ ! -d "$abs_dir_path" ]; then
      log_warn_action "Directorio no encontrado: $abs_dir_path"
      echo "$output"
      return 0
    fi

    local linked_items=$'\n'
    local item
    while IFS= read -r item; do
      [ -z "$item" ] && continue
      if is_debug; then
        echo "Item: $(print_path "${item//\\/\\\\}")" >&2
        echo "Target: $(print_path "$target")" >&2
        echo "-----------" >&2
      fi
      linked_items+="$item"$'\n'
      add_with_collision_check "$item"
    done < <(list_glob_sources "$abs_dir_path" "$descend_into_pat" "$effective_exclude_pat" "$marker_file")

    if [ -n "$conditional_exclude_pat" ]; then
      while IFS= read -r item; do
        [ -z "$item" ] && continue
        if [[ "$linked_items" == *$'\n'"$item"$'\n'* ]]; then
          continue
        fi
        add_stale_symlink_removal "$item"
      done < <(list_glob_sources "$abs_dir_path" "$descend_into_pat" "$exclude_pat" "$marker_file")
    fi
  else
    output=$(add_path_to_output "$path" "$target" "$output" "$uses_exact_target" "$hard_link")
  fi

  unset -f add_stale_symlink_removal
  unset -f add_with_collision_check
  echo "$output"
}

get_paths() {
  local selector="$1"
  local selector_override="$2"
  local output="[]"
  local entries
  entries=$(yq eval -o=json ".paths[] | select($selector)" "$CONFIG_PATHS_FILE" | jq -c '.')
  local total_entries
  total_entries=$(printf "%s\n" "$entries" | awk 'NF { count++ } END { print count + 0 }')
  local entry_index=0

  while read -r line; do
    [ -z "$line" ] && continue
    entry_index=$((entry_index + 1))
    printf "%s/%s %s\n" "$entry_index" "$total_entries" "$(echo "$line" | jq -r '.path')" > "$RESOLVE_PROGRESS_FILE"
    output=$(echo "$output" | jq -c ". + $(process_path_entry "$line" "$selector_override")")
  done <<< "$entries"

  echo "$output"
}

retrieve_linux_paths() {
  local current_distro
  current_distro=$(get_linux_distro)
  local wsl_status="false"
  if is_wsl; then
    wsl_status="true"
  fi

  local selector='(
    .excludeFor == null or (
      [
        .excludeFor[]? |
        select(
          (
            .platform == null and
            .wsl != null and
            .wsl == '$wsl_status'
          ) or (
            .platform == "linux" and
            (.linuxDistro == null or .linuxDistro == "'$current_distro'")
          )
        )
      ] | length == 0
    )
  ) and (
    .onlyFor == null or (
      [
        .onlyFor[]? |
        select(
          (
            .platform == null and
            .wsl != null and
            .wsl == '$wsl_status'
          ) or (
            .platform == "linux" and
            (.linuxDistro == null or .linuxDistro == "'$current_distro'")
          )
        )
      ] | length > 0
    )
  )'

  local selector_override='((.platform == "linux") and
    (.linuxDistro == null or .linuxDistro == "'$current_distro'")) or
    (.platform == null and .wsl != null and .wsl == '$wsl_status')'

  get_paths "$selector" "$selector_override"
}

retrieve_darwin_paths() {
  local selector='(
    .excludeFor == null or ([.excludeFor[]? | select(.platform == "darwin")] | length == 0)
  ) and (
    .onlyFor == null or ([.onlyFor[]? | select(.platform == "darwin")] | length > 0)
  )'
  local selector_override='.platform == "darwin"'

  get_paths "$selector" "$selector_override"
}

retrieve_paths_for_platform() {
  if is_darwin; then
    retrieve_darwin_paths
  else
    retrieve_linux_paths
  fi
}


print_summary_cell() {
  local icon="$1"
  local label="$2"
  local value="$3"
  printf "%s%s %4s" "$(icon_prefix "$icon")" "$(pad_text "$label" 14)" "$value"
}

print_summary() {
  local end_time_seconds
  end_time_seconds=$(date +%s)
  local total_elapsed_seconds=$((end_time_seconds - START_TIME_SECONDS))
  local column_gap="     "
  local mode_text="$(icon_prefix "$ICON_REAL_RUN")aplicación real"
  if [ "$DRY_RUN" = "true" ]; then
    mode_text="$(icon_prefix "$ICON_DRY_RUN")simulación, no se escribieron cambios"
  fi

  local errors_cell
  errors_cell=$(print_summary_cell "$ICON_ERROR" "errores" "$COUNT_ERRORS")
  if [ "$COUNT_ERRORS" -gt 0 ]; then
    errors_cell=$(print_red -b "$errors_cell")
  fi

  local status_text
  if [ "$COUNT_ERRORS" -eq 0 ]; then
    status_text=$(print_green -b "$(icon_prefix "$ICON_DONE")Sin errores.")
  else
    status_text=$(print_red -b "$(icon_prefix "$ICON_FAILED")Finalizado con $COUNT_ERRORS error(es).")
  fi

  print_block_gap
  print_box_top "$(icon_prefix "$ICON_SUMMARY")Resumen"
  print_box_row "$(print_green -b "$(print_summary_cell "$ICON_CREATED" "creados" "$COUNT_CREATED")")$column_gap$(print_blue -b "$(print_summary_cell "$ICON_REPLACED" "reemplazados" "$COUNT_REPLACED")")"
  print_box_row "$(print_summary_cell "$ICON_UNCHANGED" "sin cambios" "$COUNT_UNCHANGED")$column_gap$(print_summary_cell "$ICON_DELETE" "eliminados" "$COUNT_REMOVED")"
  print_box_row "$(print_summary_cell "$ICON_BACKUP" "respaldos" "$COUNT_BACKUPS")$column_gap$errors_cell"
  if [ "$COUNT_SUDO_OPERATIONS" -gt 0 ] || [ "$COUNT_WINDOWS_QUEUED" -gt 0 ]; then
    print_box_row "$(print_summary_cell "$ICON_SUDO" "con sudo" "$COUNT_SUDO_OPERATIONS")$column_gap$(print_summary_cell "$ICON_QUEUED" "Windows (PS)" "$COUNT_WINDOWS_QUEUED")"
  fi
  print_box_divider
  print_box_row "$mode_text $(print_gray -b "$DISPLAY_SEPARATOR") $(icon_prefix "$ICON_TIME")${total_elapsed_seconds}s $(print_gray -b "$DISPLAY_SEPARATOR") $status_text"
  print_box_bottom
  LAST_OUTPUT_WAS_BLANK=false
}

print_diagnostics() {
  if [ ! -s "$FAILED_TARGETS_FILE" ]; then
    return 0
  fi

  print_block_gap
  print_box_top "$(icon_prefix "$ICON_DIAGNOSTIC")Diagnóstico"

  local diagnostic_index=1
  while IFS=$'\t' read -r failed_target failed_reason; do
    [ -z "$failed_target" ] && continue
    print_box_row "$(print_red -b "$diagnostic_index.") $(print_path "$(display_target_path "$failed_target")")"
    print_box_row "   $(print_gray -b "$POINTER $failed_reason")"
    diagnostic_index=$((diagnostic_index + 1))
  done < "$FAILED_TARGETS_FILE"
  print_box_bottom
  LAST_OUTPUT_WAS_BLANK=false
}

print_banner() {
  can_print_details || return 0

  local mode_text="$(icon_prefix "$ICON_REAL_RUN")aplicación real"
  if [ "$DRY_RUN" = "true" ]; then
    mode_text="$(icon_prefix "$ICON_DRY_RUN")simulación: no se escriben cambios"
  fi

  print_box_top ""
  print_box_row "$(print_magenta -b "$(icon_prefix "$ICON_APP")dotfiler") $(print_gray -b "$DISPLAY_SEPARATOR") $mode_text"
  print_box_row "$(print_gray -b "$(icon_prefix "$ICON_SOURCE")$(display_target_path "$ROOT_CONFIGS_DIR")  $POINTER  $(icon_prefix "$ICON_HOME")~")"
  print_box_bottom
  LAST_OUTPUT_WAS_BLANK=false
}

main() {
  parse_args "$@"
  apply_icon_mode

  check_commands yq jq
  if ! validate_paths_config; then
    print_diagnostics
    return "$EXIT_CODE_INPUT_ERROR"
  fi

  USERNAME=$(get_windows_username)

  print_banner

  local paths
  start_spinner
  paths="$(retrieve_paths_for_platform)"
  stop_spinner
  local last_group=""
  ITEM_NAME_WIDTH=$(resolve_item_name_width "$paths")
  local total_operations
  total_operations=$(echo "$paths" | jq 'length')
  local operation_index=0
  if progress_is_enabled; then
    printf "\033[?25l" >&2
  fi

  while read -r line; do
    if [ -z "$line" ]; then
      continue
    fi

    local path
    path=$(echo "$line" | jq -r '.path')
    local target
    target=$(echo "$line" | jq -r '.target')
    local hard_link
    hard_link=$(echo "$line" | jq -r 'if .hardLink == true then "true" else "false" end')
    local remove_link
    remove_link=$(echo "$line" | jq -r 'if .remove == true then "true" else "false" end')
    local removal_reason
    removal_reason=$(echo "$line" | jq -r '.reason // empty')
    operation_index=$((operation_index + 1))
    render_linking_progress "$operation_index" "$total_operations" "$(basename "$target")"

    local current_group
    current_group=$(display_target_path "$(dirname "$target")")

    if [ "$current_group" != "$last_group" ]; then
      flush_group_unchanged_count
      print_group_header "$current_group"
      last_group="$current_group"
    fi

    if [ "$remove_link" = "true" ]; then
      if ! remove_stale_symlink "$path" "$target" "$removal_reason"; then
        COUNT_ERRORS=$((COUNT_ERRORS + 1))
      fi
    elif ! make_symlink "$path" "$target" "$hard_link"; then
      COUNT_ERRORS=$((COUNT_ERRORS + 1))
    fi
  done < <(echo "$paths" | jq -c "$SORT_BY_TARGET_GROUP_FILTER")

  flush_group_unchanged_count
  stop_spinner

  if [ "$COUNT_UNCHANGED" -gt 0 ] && [ "$VERBOSE" != "true" ] && can_print_details &&
    [ $((COUNT_CREATED + COUNT_REPLACED + COUNT_REMOVED + COUNT_BACKUPS + COUNT_WINDOWS_QUEUED)) -eq 0 ]; then
    print_block_gap
    printf "%s\n" "$(print_green -b "$(icon_prefix "$ICON_UNCHANGED")Todos los enlaces están al día ($COUNT_UNCHANGED).")"
    LAST_OUTPUT_WAS_BLANK=false
  fi

  if ! run_elevated_powershell_script "$TMP_SCRIPT"; then
    COUNT_ERRORS=$((COUNT_ERRORS + 1))
  fi

  # Reconcile errors recorded inside command substitution subshells
  # (e.g. add_path_to_output during retrieve_paths_for_platform) so that
  # the summary and exit code reflect failures that the in-process
  # COUNT_ERRORS counter could not observe.
  local recorded_failures
  recorded_failures=$(recorded_failure_count)
  if [ "$recorded_failures" -gt "$COUNT_ERRORS" ]; then
    COUNT_ERRORS="$recorded_failures"
  fi

  print_summary
  print_diagnostics

  if [ "$COUNT_ERRORS" -gt 0 ]; then
    return "$EXIT_CODE_RUNTIME_ERROR"
  fi

  return "$EXIT_CODE_SUCCESS"
}

if [ "$EUID" = 0 ]; then
  log_error_action "No ejecutes este script como root."
  exit "$EXIT_CODE_INPUT_ERROR"
fi

main "$@"
