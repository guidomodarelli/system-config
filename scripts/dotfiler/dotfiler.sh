path_is_inside_configs_dir() {
  local path="$1"
  local resolved_path
  local resolved_configs_dir

  resolved_path=$(realpath "$path" 2>/dev/null) || return 1
  resolved_configs_dir=$(realpath "$ROOT_CONFIGS_DIR" 2>/dev/null) || return 1
  [ "$resolved_path" = "$resolved_configs_dir" ] || [[ "$resolved_path" == "$resolved_configs_dir/"* ]]
}

is_directory_replacement_planned() {
  local target_dir="$1"
  [[ "$PLANNED_DIRECTORY_REPLACEMENTS" == *$'\n'"$target_dir"$'\n'* ]]
}

# Replaces a directory symlink left by a previous run (pointing inside the
# repository configs) with a real directory, and refuses to create links in a
# destination that still resolves inside the repository.
prepare_target_directory() {
  local target_dir="$1"
  shift
  local -a command_prefix=("$@")

  if [ -L "$target_dir" ] && path_is_inside_configs_dir "$target_dir"; then
    local replacement_detail
    replacement_detail="(antes symlink a $(display_source_path "$(realpath "$target_dir")"))"

    if [ "$DRY_RUN" = "true" ]; then
      if ! is_directory_replacement_planned "$target_dir"; then
        PLANNED_DIRECTORY_REPLACEMENTS+="$target_dir"$'\n'
        COUNT_REMOVED=$((COUNT_REMOVED + 1))
        print_item_line print_blue "$ICON_DIRECTORY" "carpeta real" "$(basename "$target_dir")" "$replacement_detail"
      fi
      return 0
    fi

    if ! "${command_prefix[@]}" rm "$target_dir"; then
      log_error_action "No se pudo eliminar symlink de directorio $(print_path "$target_dir")"
      record_failed_target "$target_dir" "Fallo al reemplazar symlink de directorio por carpeta real"
      return 1
    fi
    COUNT_REMOVED=$((COUNT_REMOVED + 1))
    print_item_line print_blue "$ICON_DIRECTORY" "carpeta real" "$(basename "$target_dir")" "$replacement_detail"
    return 0
  fi

  if [ "$DRY_RUN" = "true" ] && is_directory_replacement_planned "$target_dir"; then
    return 0
  fi

  if [ -e "$target_dir" ] && path_is_inside_configs_dir "$target_dir"; then
    log_error_action "El directorio destino resuelve dentro del repositorio: $(print_path "$target_dir")"
    record_failed_target "$target_dir" "Directorio destino dentro del repositorio"
    return 1
  fi
}

# This function creates a symbolic link from the source path to the target location
# It handles existing files by creating backups and removes old symlinks if they exist
make_symlink() {
  local path="$1"
  local target="$2"
  local hard_link="${3:-false}"
  local link_type="$LINK_TYPE_SYMLINK"
  local powershell_link_type="$POWERSHELL_LINK_TYPE_SYMLINK"
  local item_name
  item_name=$(basename "$target")
  local started_at_seconds
  started_at_seconds=$(date +%s)

  if [ "$hard_link" = "true" ]; then
    link_type="$LINK_TYPE_HARD"
    powershell_link_type="$POWERSHELL_LINK_TYPE_HARD"
    if [[ ! "$path" =~ "\\\\wsl\$" ]] && [ ! -f "$path" ]; then
      log_error_action "No se puede crear hard link: el origen no es un archivo regular $(print_path "$path")"
      record_failed_target "$target" "Hard link requiere un archivo regular"
      return 1
    fi
  fi

  local -a command_prefix=()
  local target_dir
  target_dir=$(dirname "$target")

  if needs_elevated_permissions "$target" "$target_dir"; then
    command_prefix=(sudo)
    COUNT_SUDO_OPERATIONS=$((COUNT_SUDO_OPERATIONS + 1))
    print_item_line print_yellow "$ICON_SUDO" "sudo" "$item_name" "(permisos elevados)"
  fi

  if ! prepare_target_directory "$target_dir" "${command_prefix[@]}"; then
    return 1
  fi

  # In dry-run the directory symlink is still in place, so existing entries
  # would be read through it; the replaced directory will start empty.
  local target_dir_pending_replacement="false"
  if [ "$DRY_RUN" = "true" ] && is_directory_replacement_planned "$target_dir"; then
    target_dir_pending_replacement="true"
  fi

  if [ "$target_dir_pending_replacement" != "true" ] && link_is_already_correct "$path" "$target" "$hard_link"; then
    COUNT_UNCHANGED=$((COUNT_UNCHANGED + 1))
    GROUP_UNCHANGED_COUNT=$((GROUP_UNCHANGED_COUNT + 1))
    if [ "$VERBOSE" = "true" ]; then
      print_item_line print_gray "$ICON_UNCHANGED" "sin cambios" "$item_name" "$(print_link_detail "$path" "$link_type")"
      GROUP_CHANGE_COUNT=$((GROUP_CHANGE_COUNT - 1))
    fi
    return 0
  fi

  if [ "$target_dir_pending_replacement" != "true" ] && [ -L "${target}.bak" ]; then
    if ! remove_old_symlink "${target}.bak" "${command_prefix[@]}"; then
      return 1
    fi
    COUNT_REMOVED=$((COUNT_REMOVED + 1))
    print_item_line print_red "$ICON_DELETE" "eliminado" "$item_name.bak" "(symlink de respaldo obsoleto)"
  fi

  local link_action="created"
  if [ "$target_dir_pending_replacement" = "true" ]; then
    COUNT_CREATED=$((COUNT_CREATED + 1))
  elif [ -L "$target" ]; then
    if ! remove_old_symlink "$target" "${command_prefix[@]}"; then
      return 1
    fi
    link_action="replaced"
    COUNT_REPLACED=$((COUNT_REPLACED + 1))
  elif [ -e "$target" ]; then
    if ! create_backup "$target" "${command_prefix[@]}"; then
      return 1
    fi
    link_action="replaced"
    COUNT_REPLACED=$((COUNT_REPLACED + 1))
  else
    COUNT_CREATED=$((COUNT_CREATED + 1))
  fi

  if [ "$DRY_RUN" != "true" ]; then
    if ! "${command_prefix[@]}" mkdir -p "$(dirname "$target")"; then
      log_error_action "No se pudo crear directorio padre para $(print_path "$target")"
      record_failed_target "$target" "Fallo al crear directorio padre"
      return 1
    fi
  fi

  if [[ $path =~ "\\\\wsl\$" ]]; then
    if [ "$DRY_RUN" != "true" ]; then
      local win_target ps_target ps_source
      win_target=$(wslpath -w "$target" 2>/dev/null)
      ps_target="${win_target//\'/\'\'}"
      ps_source="${path//\'/\'\'}"
      echo "New-Item -ItemType $powershell_link_type -Path '$ps_target' -Target '$ps_source' -Force" >> "$TMP_SCRIPT"
    fi
    COUNT_WINDOWS_QUEUED=$((COUNT_WINDOWS_QUEUED + 1))
    print_item_line print_blue "$ICON_QUEUED" "en cola (PS)" "$item_name" "$(print_link_detail "$path" "$link_type")"
  else
    if [ "$DRY_RUN" != "true" ]; then
      local -a link_arguments=()
      if [ "$hard_link" != "true" ]; then
        link_arguments=(-s)
      fi

      if ! "${command_prefix[@]}" ln "${link_arguments[@]}" "$path" "$target"; then
        log_error_action "No se pudo crear $link_type $(print_path "$target") -> $(print_path "${path//\\/\\\\}")"
        record_failed_target "$target" "Fallo al crear $link_type"
        return 1
      fi
    fi
  fi

  if [[ ! $path =~ "\\\\wsl\$" ]]; then
    if [ "$link_action" = "replaced" ]; then
      print_item_line print_blue "$ICON_REPLACED" "reemplazado" "$item_name" "$(print_link_detail "$path" "$link_type")"
    else
      print_item_line print_green "$ICON_CREATED" "creado" "$item_name" "$(print_link_detail "$path" "$link_type")"
    fi
  fi
  print_operation_duration "$started_at_seconds"

  return 0
}

# Removes a symlink left by a previous run whose source is now excluded by an
# active `conditionalExcludes` rule.
remove_stale_symlink() {
  local path="$1"
  local target="$2"
  local reason="${3:-}"
  local -a command_prefix=()
  local item_name
  item_name=$(basename "$target")
  local removal_detail="(excluido por condición)"
  if [ -n "$reason" ]; then
    removal_detail="(excluido por $reason)"
  fi

  if ! symlink_points_to_source "$target" "$path"; then
    return 0
  fi

  if needs_elevated_permissions "$target" "$(dirname "$target")"; then
    command_prefix=(sudo)
    COUNT_SUDO_OPERATIONS=$((COUNT_SUDO_OPERATIONS + 1))
    print_item_line print_yellow "$ICON_SUDO" "sudo" "$item_name" "(permisos elevados)"
  fi

  if [ "$DRY_RUN" != "true" ] && ! "${command_prefix[@]}" rm "$target"; then
    log_error_action "No se pudo eliminar symlink excluido por condición $(print_path "$target")"
    record_failed_target "$target" "Fallo al eliminar symlink excluido por condición"
    return 1
  fi

  COUNT_REMOVED=$((COUNT_REMOVED + 1))
  print_item_line print_red "$ICON_DELETE" "eliminado" "$item_name" "$removal_detail"
}

# True when the destination already is the requested link, so it can be left
# untouched instead of being removed and recreated.
link_is_already_correct() {
  local path="$1"
  local target="$2"
  local hard_link="$3"

  if [[ $path =~ "\\\\wsl\$" ]]; then
    return 1
  fi

  if [ "$hard_link" = "true" ]; then
    [ ! -L "$target" ] && [ -f "$target" ] && [ "$target" -ef "$path" ]
    return $?
  fi

  [ -L "$target" ] && [ "$(readlink "$target")" = "$path" ]
}

